class Solution {
public:
    long long countCommas(long long n) {
        long long commas = 0;

        if(n < 1000){
            return commas;
        }

        if(n >= 1000 && n < 1000000){
            commas = n - 1000 + 1;
        }

        if(n >= 1000000 && n < 1000000000){
            commas = 1000000 - 1000;
            commas += (n - 1000000 + 1) * 2;
        }

        if(n >= 1000000000 && n < 1000000000000){
            commas = 1000000 - 1000;
            commas += (1000000000 - 1000000) * 2;
            commas += (n - 1000000000 + 1) * 3;
        }

        if(n >= 1000000000000 && n < 1000000000000000){
            commas = 1000000 - 1000;
            commas += (1000000000 - 1000000) * 2;
            commas += (1000000000000 - 1000000000) * 3;
            commas += (n - 1000000000000 + 1) * 4;
        }

        if(n >= 1000000000000000){
            commas = 1000000 - 1000;
            commas += (1000000000 - 1000000) * 2;
            commas += (1000000000000 - 1000000000) * 3;
            commas += (1000000000000000 - 1000000000000) * 4;
            commas += (n - 1000000000000000 + 1) * 5;
        }

        return commas;

    }
};